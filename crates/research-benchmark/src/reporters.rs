use super::metrics::BenchmarkReport;

/// Generate benchmark reports in multiple formats.
pub struct ReportGenerator;

impl ReportGenerator {
    /// Generate a JSON report from a BenchmarkReport.
    pub fn to_json(report: &BenchmarkReport) -> anyhow::Result<String> {
        Ok(serde_json::to_string_pretty(report)?)
    }

    /// Generate a markdown report from a BenchmarkReport.
    pub fn to_markdown(report: &BenchmarkReport) -> String {
        let mut md = format!(
            "# Benchmark Report: {}\n\n\
             **Runs per provider:** {}\n\n",
            report.skill_name, report.runs_per_provider
        );

        // Summary scores
        md.push_str("## Summary Scores\n\n");
        md.push_str(&format!(
            "| Metric | Score |\n|--------|-------|\n\
             | Agreement | {:.1}% |\n\
             | Stability | {:.1}% |\n\
             | Cost Efficiency | {:.1}% |\n\
             | Latency Efficiency | {:.1}% |\n\
             | Schema Pass Rate | {:.1}% |\n",
            report.agreement_score * 100.0,
            report.stability_score * 100.0,
            report.cost_score * 100.0,
            report.latency_score * 100.0,
            report.schema_pass_rate * 100.0,
        ));
        if let Some(gt) = report.ground_truth_score {
            md.push_str(&format!("| Ground Truth | {:.1}% |\n", gt * 100.0));
        }
        md.push('\n');

        // Provider Ranking
        md.push_str("## Provider Ranking\n\n");
        md.push_str(
            "| Rank | Provider | Regime Accuracy | Cost Eff. | Stability | Overall |\n"
        );
        md.push_str(
            "|------|----------|-----------------|-----------|-----------|---------|\n"
        );
        for (rank, score) in report.provider_ranking.iter().enumerate() {
            md.push_str(&format!(
                "| {} | {} | {:.1}% | {:.1}% | {:.1}% | {:.1}% |\n",
                rank + 1,
                score.provider,
                score.regime_accuracy * 100.0,
                score.cost_efficiency * 100.0,
                score.stability * 100.0,
                score.overall * 100.0,
            ));
        }
        md.push('\n');

        // Winner
        if let Some(winner) = report.provider_ranking.first() {
            md.push_str(&format!(
                "**Winner:** {} (overall score: {:.1}%)\n\n",
                winner.provider,
                winner.overall * 100.0
            ));
        }

        // Divergence points
        if !report.divergence_points.is_empty() {
            md.push_str("## Divergence Points\n\n");
            for point in &report.divergence_points {
                md.push_str(&format!(
                    "### `{}` (agreement: {:.1}%)\n\n",
                    point.field,
                    point.agreement_ratio * 100.0
                ));
                for (provider, value) in &point.values {
                    md.push_str(&format!("- **{}**: `{}`\n", provider, value));
                }
                md.push('\n');
            }
        }

        md.push_str("---\n\n");
        md.push_str(
            "*Benchmark generated by research-benchmark. \
             Ground-truth scoring requires labeled dataset.*"
        );

        md
    }
}
